// notices writes THIRD_PARTY_NOTICES.md: the license of every module
// linked into the packages of this module on any supported platform, read
// from the module cache, plus the Go standard library notice.
//
//	go run ./internal/tools/notices > THIRD_PARTY_NOTICES.md
package main

import (
	"bytes"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type module struct {
	path, version, dir string
}

// platforms are the GOOS/GOARCH pairs whose dependency sets are credited:
// the CI runners, the cross builds, and the common desktop targets.
var platforms = [][2]string{
	{"linux", "amd64"}, {"linux", "arm64"},
	{"darwin", "amd64"}, {"darwin", "arm64"},
	{"windows", "amd64"}, {"windows", "arm64"},
	{"js", "wasm"},
}

var licenseName = regexp.MustCompile(`(?i)^(LICENSE|LICENCE|COPYING|NOTICE)(\.(txt|md|rst))?$`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	// List the packages actually built, so only linked modules are credited,
	// on every platform the module supports: the dependency set differs by
	// target (x/image/vector pulls x/sys/cpu on amd64 alone), and the output
	// must not depend on the machine that generated it. Credit versioned
	// replacements under their own name; local ones keep ours. The standard
	// library has no module and the main module is excluded.
	modules := map[string]module{}
	for _, platform := range platforms {
		cmd := exec.Command("go", "list", "-deps", "-f", `{{with .Module}}{{if not .Main}}{{$m := .}}{{with .Replace}}{{if .Version}}{{$m = .}}{{end}}{{end}}{{with $m}}{{.Path}}	{{.Version}}	{{.Dir}}{{end}}{{end}}{{end}}`, "./...")
		cmd.Env = append(os.Environ(), "GOOS="+platform[0], "GOARCH="+platform[1])
		out, err := cmd.Output()
		if err != nil {
			return fmt.Errorf("go list for %s/%s: %w", platform[0], platform[1], err)
		}
		for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
			fields := strings.Split(line, "\t")
			if len(fields) != 3 || fields[2] == "" {
				continue
			}
			if _, seen := modules[fields[0]]; !seen {
				modules[fields[0]] = module{fields[0], fields[1], fields[2]}
			}
		}
	}
	var paths []string
	for p := range modules {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString(`# Third-party notices

nttypeset is MIT licensed; see LICENSE. The Go standard library and the
dependencies below are used by it. Generated by internal/tools/notices.

`)

	// The Go runtime and standard library are compiled into every binary.
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return err
	}
	text, err := goLicense(strings.TrimSpace(string(goroot)))
	if err != nil {
		return err
	}
	section(&b, "The Go runtime and standard library", "https://go.dev", text)
	var missing []string
	for _, p := range paths {
		m := modules[p]
		entries, err := os.ReadDir(m.dir)
		if err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		var texts [][]byte
		for _, e := range entries {
			if !e.IsDir() && licenseName.MatchString(e.Name()) {
				text, err := os.ReadFile(filepath.Join(m.dir, e.Name()))
				if err != nil {
					return err
				}
				texts = append(texts, text)
			}
		}
		if len(texts) == 0 {
			missing = append(missing, p)
			continue
		}
		section(&b, m.path+" "+m.version, "", bytes.Join(texts, []byte("\n\n")))
	}
	if len(missing) > 0 {
		return fmt.Errorf("no license file in: %s", strings.Join(missing, ", "))
	}
	_, err = os.Stdout.Write(append(bytes.TrimRight(b.Bytes(), "\n"), '\n'))
	return err
}

// Homebrew keeps Go in libexec and its license in the enclosing keg.
func goLicense(root string) ([]byte, error) {
	root = filepath.Clean(root)
	name := filepath.Join(root, "LICENSE")
	text, err := os.ReadFile(name)
	if os.IsNotExist(err) && filepath.Base(root) == "libexec" {
		parent := filepath.Join(filepath.Dir(root), "LICENSE")
		text, err = os.ReadFile(parent)
		if err != nil {
			return nil, fmt.Errorf("runtime license for Go (checked %s and %s): %w", name, parent, err)
		}
	}
	if err != nil {
		return nil, fmt.Errorf("runtime license for Go %s: %w", name, err)
	}
	return text, nil
}

func section(b *bytes.Buffer, title, note string, text []byte) {
	fmt.Fprintf(b, "## %s\n\n", title)
	if note != "" {
		fmt.Fprintf(b, "%s\n\n", note)
	}
	b.WriteString("```\n")
	b.Write(bytes.TrimRight(text, "\n"))
	b.WriteString("\n```\n\n")
}
