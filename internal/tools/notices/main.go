// notices writes THIRD_PARTY_NOTICES.md: the license of every module
// the main module depends on, read from the module cache, plus the Go
// standard library notice.
//
//	go run ./internal/tools/notices > THIRD_PARTY_NOTICES.md
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

type module struct {
	Path    string
	Version string
	Dir     string
	Main    bool
	Replace *module
}

var licenseName = regexp.MustCompile(`(?i)^(LICENSE|LICENCE|COPYING|NOTICE)(\.(txt|md|rst))?$`)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
}

func run() error {
	out, err := exec.Command("go", "list", "-m", "-json", "all").Output()
	if err != nil {
		return fmt.Errorf("go list -m: %w", err)
	}
	modules := map[string]module{}
	dec := json.NewDecoder(bytes.NewReader(out))
	for {
		var m module
		if err := dec.Decode(&m); err == io.EOF {
			break
		} else if err != nil {
			return err
		}
		if m.Main {
			continue
		}
		// Credit a versioned replacement under its own name; local ones keep ours.
		if m.Replace != nil && m.Replace.Version != "" {
			m = *m.Replace
		}
		// Modules whose sources are not in the cache are not linked in.
		if m.Dir == "" {
			continue
		}
		modules[m.Path] = m
	}
	var paths []string
	for p := range modules {
		paths = append(paths, p)
	}
	sort.Strings(paths)

	var b bytes.Buffer
	b.WriteString(`# Third-party notices

nttypeset is MIT licensed; see LICENSE. The Go standard library and the
dependencies below are used by it. Generated by internal/tools/notices.

`)

	// The Go runtime and standard library are compiled into every binary.
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return err
	}
	text, err := goLicense(strings.TrimSpace(string(goroot)))
	if err != nil {
		return err
	}
	section(&b, "The Go runtime and standard library", "https://go.dev", text)
	var missing []string
	for _, p := range paths {
		m := modules[p]
		entries, err := os.ReadDir(m.Dir)
		if err != nil {
			return fmt.Errorf("%s: %w", p, err)
		}
		var texts [][]byte
		for _, e := range entries {
			if !e.IsDir() && licenseName.MatchString(e.Name()) {
				text, err := os.ReadFile(filepath.Join(m.Dir, e.Name()))
				if err != nil {
					return err
				}
				texts = append(texts, text)
			}
		}
		if len(texts) == 0 {
			missing = append(missing, p)
			continue
		}
		section(&b, m.Path+" "+m.Version, "", bytes.Join(texts, []byte("\n\n")))
	}
	if len(missing) > 0 {
		return fmt.Errorf("no license file in: %s", strings.Join(missing, ", "))
	}
	_, err = os.Stdout.Write(append(bytes.TrimRight(b.Bytes(), "\n"), '\n'))
	return err
}

// Homebrew keeps Go in libexec and its license in the enclosing keg.
func goLicense(root string) ([]byte, error) {
	root = filepath.Clean(root)
	name := filepath.Join(root, "LICENSE")
	text, err := os.ReadFile(name)
	if os.IsNotExist(err) && filepath.Base(root) == "libexec" {
		parent := filepath.Join(filepath.Dir(root), "LICENSE")
		text, err = os.ReadFile(parent)
		if err != nil {
			return nil, fmt.Errorf("runtime license for Go (checked %s and %s): %w", name, parent, err)
		}
	}
	if err != nil {
		return nil, fmt.Errorf("runtime license for Go %s: %w", name, err)
	}
	return text, nil
}

func section(b *bytes.Buffer, title, note string, text []byte) {
	fmt.Fprintf(b, "## %s\n\n", title)
	if note != "" {
		fmt.Fprintf(b, "%s\n\n", note)
	}
	b.WriteString("```\n")
	b.Write(bytes.TrimRight(text, "\n"))
	b.WriteString("\n```\n\n")
}
